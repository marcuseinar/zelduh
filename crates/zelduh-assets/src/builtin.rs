//! The art that ships with the engine.
//!
//! Everything here is drawn as string art so it can be edited by hand: `.` is
//! transparent (or the palette's first colour on terrain), `-` `+` `#` are the
//! other three. Ground textures are usually 8x8 and repeat across the 16x16
//! terrain square; anything with a silhouette is drawn at full size.
//!
//! None of this is copied from any commercial game; it is original art in the
//! same 4-colour idiom, so the engine has something to draw before anyone
//! points it at a ROM.

use crate::pack::{AssetPack, PackBuilder, SpriteId};
use crate::palette::pal;
use zelduh_core::tiles::tile;

/// Builds the default asset pack.
pub fn pack() -> AssetPack {
    let mut b = PackBuilder::new("built-in");
    terrain(&mut b);
    hero(&mut b);
    monsters(&mut b);
    objects(&mut b);
    hud(&mut b);
    b.build()
}

