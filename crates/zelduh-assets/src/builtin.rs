#[cfg(test)]
mod tests {
    use super::*;
    use crate::tile::Cell;
    use zelduh_core::tiles::tile;

    #[test]
    fn the_pack_draws_every_terrain_tile_the_generator_uses() {
        let p = pack();
        for t in [
            tile::GRASS,
            tile::GRASS_TALL,
            tile::SAND,
            tile::PATH,
            tile::FLOOR,
            tile::WATER,
            tile::BUSH,
            tile::ROCK,
            tile::TREE,
            tile::WALL,
            tile::WALL_DUNGEON,
            tile::WALL_CRACKED,
            tile::DOOR_OPEN,
            tile::DOOR_SHUT,
            tile::DOOR_LOCKED,
            tile::DOOR_BOSS,
            tile::STAIRS_DOWN,
            tile::STAIRS_UP,
            tile::PIT,
            tile::LEDGE_DOWN,
            tile::LEDGE_UP,
            tile::LEDGE_LEFT,
            tile::LEDGE_RIGHT,
        ] {
            let m = p.metatile(t);
            assert!(
                m.iter().any(|c| !c.is_blank()),
                "terrain {t} has no art at all"
            );
        }
    }

    #[test]
    fn every_sprite_slot_is_filled() {
        let p = pack();
        for i in 0..SpriteId::N {
            let s = &p.sprites[i];
            assert!(s.cols > 0 && s.rows > 0, "sprite {i} is empty");
            assert!(
                s.cells.iter().any(|c: &Cell| !c.is_blank()),
                "sprite {i} draws nothing"
            );
        }
    }

    #[test]
    fn identical_art_is_shared() {
        let p = pack();
        // Far fewer unique tiles than cells, because flat areas repeat.
        let cells: usize =
            p.sprites.iter().map(|s| s.cells.len()).sum::<usize>() + p.metatiles.len() * 4;
        assert!(
            p.tile_count() < cells,
            "expected tile sharing: {} tiles for {cells} cells",
            p.tile_count()
        );
    }

    #[test]
    fn the_boss_is_bigger_than_a_hero() {
        let p = pack();
        assert!(p.sprite(SpriteId::Boss0).width() > p.sprite(SpriteId::HeroDown0).width());
    }
}
