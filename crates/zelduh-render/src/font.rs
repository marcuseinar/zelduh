/// True when the glyph has a pixel at `(x, y)`.
pub fn pixel(c: char, x: i32, y: i32) -> bool {
    if !(0..5).contains(&x) || !(0..HEIGHT).contains(&y) {
        return false;
    }
    let c = c.to_ascii_uppercase();
    let c = if c == 'X' { 'X' } else { c };
    let Some((_, rows)) = GLYPHS.iter().find(|(g, _)| g.to_ascii_uppercase() == c) else {
        return false;
    };
    rows[y as usize].as_bytes()[x as usize] == b'#'
}

/// Width in pixels of a string drawn with this font.
pub fn width(text: &str) -> i32 {
    text.chars().count() as i32 * ADVANCE
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_five_wide_and_seven_tall() {
        for (c, rows) in GLYPHS {
            for (i, r) in rows.iter().enumerate() {
                assert_eq!(r.len(), 5, "glyph {c} row {i} is the wrong width");
            }
        }
    }

    #[test]
    fn letters_and_digits_are_all_present() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789".chars() {
            assert!(
                GLYPHS.iter().any(|(g, _)| *g == c),
                "missing a glyph for {c}"
            );
        }
    }

    #[test]
    fn unknown_characters_draw_nothing() {
        assert!(!pixel('~', 0, 0));
        assert!(!pixel(' ', 2, 3));
    }

    #[test]
    fn lookup_is_case_insensitive() {
        for y in 0..HEIGHT {
            for x in 0..5 {
                assert_eq!(pixel('a', x, y), pixel('A', x, y));
            }
        }
    }

    #[test]
    fn width_counts_the_gap() {
        assert_eq!(width("AB"), 12);
        assert_eq!(width(""), 0);
    }
}
